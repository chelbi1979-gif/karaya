function rxTranslate(s) {
  for (var i = 0; i < KARAYA_FR_RX.length; i++) {
    var out = s.replace(KARAYA_FR_RX[i][0], KARAYA_FR_RX[i][1]);
    if (out !== s) return out;
  }
  return s;
}

  var LSKEY = 'karaya_lang_v1';
  var AR = /[\u0600-\u06FF]/;
  var SKIP = { SCRIPT: 1, STYLE: 1, TEXTAREA: 1, CODE: 1, PRE: 1, SVG: 1 };
  var ATTRS = ['placeholder', 'title', 'aria-label'];
  var lang = 'ar';
  try { lang = localStorage.getItem(LSKEY) || 'ar'; } catch (e) {}
  if (lang !== 'fr') lang = 'ar';

  function tr(s) {
    if (s == null) return s;
    var raw = String(s);
    var lead = raw.match(/^\s*/)[0], trail = raw.match(/\s*$/)[0];
    var core = raw.trim();
    if (!core) return raw;
    var v = KARAYA_FR[core];
    if (v == null) {
      var rx = rxTranslate(core);
      return (rx !== core) ? lead + rx + trail : raw;
    }
    return lead + v + trail;
  }
  function handleText(n) {
    if (lang === 'fr') {
      if (!AR.test(n.nodeValue)) return;
      if (n.__ar == null) n.__ar = n.nodeValue;
      var t = tr(n.nodeValue);
      if (t !== n.nodeValue) n.nodeValue = t;
    } else if (n.__ar != null) {
      if (n.nodeValue !== n.__ar) n.nodeValue = n.__ar;
    }
  }
  function handleAttrs(el) {
    for (var i = 0; i < ATTRS.length; i++) {
      var a = ATTRS[i];
      if (!el.hasAttribute || !el.hasAttribute(a)) continue;
      var v = el.getAttribute(a);
      if (lang === 'fr') {
        if (!AR.test(v)) continue;
        var k = '__ar_' + a.replace(/-/g, '_');
        if (el[k] == null) el[k] = v;
        var t = tr(v);
        if (t !== v) el.setAttribute(a, t);
      } else {
        var kk = '__ar_' + a.replace(/-/g, '_');
        if (el[kk] != null) el.setAttribute(a, el[kk]);
      }
    }
  }
  function walk(node) {
    if (!node) return;
    if (node.nodeType === 3) { handleText(node); return; }
    if (node.nodeType !== 1) return;
    if (SKIP[node.nodeName]) return;
    if (node.getAttribute && node.getAttribute('data-no-i18n')) return;
    handleAttrs(node);
    for (var c = node.firstChild; c; c = c.nextSibling) walk(c);
  }
  function apply(root) {
    walk(root || document.body);
    if (document.title) document.title = lang === 'fr' ? 'Système de gestion de location' : 'نظام إدارة الكراء';
  }
  var obs = null, pending = false, queue = [];
  function startObserver() {
    if (obs || typeof MutationObserver === 'undefined') return;
    obs = new MutationObserver(function (muts) {
      for (var i = 0; i < muts.length; i++) {
        var m = muts[i];
        if (m.type === 'childList') {
          for (var j = 0; j < m.addedNodes.length; j++) queue.push(m.addedNodes[j]);
        } else if (m.type === 'characterData') queue.push(m.target);
      }
      if (pending) return;
      pending = true;
      requestAnimationFrame(function () {
        pending = false;
        var q = queue; queue = [];
        for (var k = 0; k < q.length; k++) { try { walk(q[k]); } catch (e) {} }
      });
    });
    obs.observe(document.body, { childList: true, subtree: true, characterData: true });
  }
  function paintDir() {
    var h = document.documentElement;
    h.setAttribute('lang', lang === 'fr' ? 'fr' : 'ar');
    h.setAttribute('dir', lang === 'fr' ? 'ltr' : 'rtl');
    h.classList.toggle('lang-fr', lang === 'fr');
    h.classList.toggle('lang-ar', lang === 'ar');
  }
  function setLang(l) {
    lang = (l === 'fr') ? 'fr' : 'ar';
    try { localStorage.setItem(LSKEY, lang); } catch (e) {}
    paintDir();
    apply(document.body);
    try { window.dispatchEvent(new CustomEvent('karaya:lang', { detail: { lang: lang } })); } catch (e) {}
  }
  function fmtNum(n, dec) {
    var v = Number(n) || 0;
    try {
      return v.toLocaleString(lang === 'fr' ? 'fr-FR' : 'ar-MA', {
        minimumFractionDigits: dec == null ? 2 : dec, maximumFractionDigits: dec == null ? 2 : dec
      });
    } catch (e) { return v.toFixed(dec == null ? 2 : dec); }
  }
  function fmtDate(iso) {
    if (!iso) return '';
    var s = String(iso).slice(0, 10).split('-');
    if (s.length !== 3) return String(iso);
    return lang === 'fr' ? (s[2] + '/' + s[1] + '/' + s[0]) : (s[2] + '/' + s[1] + '/' + s[0]);
  }
  function pick(o) { return (o && (lang === 'fr' ? o.fr : o.ar)) || ''; }
  function add(map) { for (var k in map) if (!(k in KARAYA_FR)) KARAYA_FR[k] = map[k]; }

